def load_data(x_path, y_path):
  """
  This funciton is meant to
  load the training features and labels
  for a neural network....
  In this case we will be using the data to
  train neural network to control voltage across
  a series RLC circuit
  """
  X = pd.read_csv(x_path, header = None)
  y = pd.read_csv(y_path, header = None)

  # Check if the lengths of the features and labels are the same or not...
  if len(X) != len(y):
    raise ValueError(f"Length mismatch! X has {len(X)} rows and y has {len(y)} rows. The number of rows for both must be equal!")
  # Check if the number of columns in X is the same as the
  # no. of features specified in the Features list....
  if X.shape[1] != len(Features):
    raise ValueError(f"The no. of columns in the features dataset {X.shape[1]} is not the same as the no. of required features. {len(Features)}!")
  # Now that all the checks are done...lets get going forward
  df = X.copy()
  df.columns = Features
  df["Controller_action"] = y.iloc[:, 0].values
  return df

"""#### 1.1.3. Functon to assign trajectory

"""

def assign_trajectory_ids(df, verbose = False):
  """
  Function to recover trajectory id automatically:
  A new trajectory starts every time the setpoint value changes.
  To recover both the 23 step response segments and the zero setpoint reset events
  """
  setpoint = df["setpoint"].values
  changed = np.empty(len(setpoint), dtype = bool)
  changed[0] = True
  changed[1:] = setpoint[1:] != setpoint[:-1]
  df[COL_TRAJECTORY_ID] = np.cumsum(changed)

  summary = (
      df.groupby(COL_TRAJECTORY_ID).agg(
          setpoint = ("setpoint", "first"),
          n_rows = ("setpoint", "size"),
          iload_min = ("Iload", "min"),
          iload_max = ("Iload", "max")
      )
  )
  if verbose:
    print(f"Auto-detected {df[COL_TRAJECTORY_ID].nunique()} trajectories"
    f"(constant-setpoint segments):")
    print(summary.to_string())

  return df

"""#### 1.1.5. Let's now get to the data splitting.

We have already specified the setpoints that we will be removing entirely for testing.
The rest are to be splitted as training and validation setpoints
"""

def split_train_val_test(df, test_setpoints, val_frac, seed):
  test_mask = df["setpoint"].isin(test_setpoints)
  test_df =  df[test_mask].copy()
  remaining_df = df[~test_mask].copy()

  remaining_trajectory_ids = remaining_df[COL_TRAJECTORY_ID].unique()
  train_ids, val_ids = train_test_split(
      remaining_trajectory_ids, test_size = val_frac, random_state = seed
  )
  train_df = remaining_df[remaining_df[COL_TRAJECTORY_ID].isin(train_ids)].copy()
  val_df = remaining_df[remaining_df[COL_TRAJECTORY_ID].isin(val_ids)].copy()

  print(f"\n Setpoints held out for testing: {sorted(df[test_mask]["setpoint"])},")
  print(f"Trajectories -> train: {len(train_ids)}, val: {len(val_ids)}, "
  f"test: {test_df[COL_TRAJECTORY_ID].nunique()}")
  print(f"Rows-> train: {len(train_df)}, val: {len(val_df)}",
        f"test: {len(test_df)}")
  return train_df, val_df, test_df

"""#### 1.1.6. Normalization

We need to normalize the training data so that the NN is able to read it easily
"""

def compute_norm_stats(df, columns):
  stats = {}
  for column in columns:
    stats[column] = {"mean": float(df[column].mean()),
                     "std": float(df[column].std() + 1e-8)}
  return stats
def apply_norm(df, columns, stats):
  out_df = df.copy()
  # Basically, we are doing the normalization done by standard scaler
  for column in columns:
    out_df[column] = (out_df[column]-stats[column]["mean"])/stats[column]["std"]
  return out_df

"""### 2. Modelling

Now we have reached the stage, where we can now build our NN model

Let's build a model, based on our already defined global variables....i.e., `hidden_layers`, `activation`, `learning rate` etc etc..
"""

def build_model(n_inputs, hidden_layers, activation, learning_rate):
  # set random seed
  tf.random.set_seed(random_seed)
  inputs = tfk.layers.Input(shape = (n_inputs,), name = "Input layer")
  x = inputs
  for hidden_units in hidden_layers:
    x = tfk.layers.Dense(hidden_units, activation = activation)(x)
  # The input and hidden layers have been defined, now onto the output layer....
  outputs = tfk.layers.Dense(1, activation = "linear", name = "control_action")(x)

  model = tfk.Model(inputs, outputs)
  # Model is defined, compile the model
  model.compile(
      loss = "mse",
      optimizer = tfk.optimizers.Adam(),
      metrics = ["mae"]
  )
  # The model has been compiled, the next step is to train it with the training data
  return model

