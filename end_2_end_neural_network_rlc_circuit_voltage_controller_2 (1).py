"""### 2.2. Function to export weights and biases to Matlab

To export the neural network to Matlab, we are going to export the weights and biases of the trained NN to a `.mat` file.
"""

def export_weights_for_matlab(model, norm_stats, input_columns, output_column, path):
  """
  Extract weights and biases from every dense layer and activation
  """
  dense_layers = [l for l in model.layers if isinstance(l, tfk.layers.Dense)]
  if not dense_layers:
    raise ValueError("No dense layers found. This export assumes a plain MLP, this architecture uses other types of layers")
  weights, biases, activations = [], [], []
  for layer in dense_layers:
    W, b = layer.get_weights()
    weights.append(W.astype(np.float64))
    biases.append(b.astype(np.float64).reshape(1, -1))
    activations.append(layer.activation.__name__) # e.g. 'relu', 'linear'

  mat_dict = {
      "num_layers": len(dense_layers),
      "input_columns": np.array(input_columns, dtype = object),
      "output_column": output_column,
      "input_mean": np.array([norm_stats[c]["mean"] for c in input_columns]).reshape(1, -1),
      "input_std": np.array([norm_stats[c]["std"] for c in input_columns]).reshape(1, -1),
      "output_mean": norm_stats[output_column]["mean"],
      "output_std": norm_stats[output_column]["std"],
      "u_min": U_min,
      "u_max": U_max
  }

  for i, (W, b, act) in  enumerate(zip(weights, biases, activations), start = 1):
    mat_dict[f"W{i}"] = W
    mat_dict[f"b{i}"] = b
    mat_dict[f"activation{i}"] = act

  sio.savemat(path, mat_dict)
  print(f"\nExported {len(dense_layers)}-layer weights for MATLAB to: {path}")
  for i, (W, act) in enumerate(zip(weights, activations)):
    print(f" Layer {i}: Weight shape {W.shape}, activation = {act}")
  # ----Self-check: perform a forward pass in numpy using these exact
  # exported arrays, on one random input and compare to model.predict.
  # If this ever mismatches, something is wrong with the export
  # perform this check before trussting the MATLAB code...
  x_check = np.random.randn(1, len(input_columns)).astype(np.float32)
  y_keras = model.predict(x_check, verbose = 0)

  x_np = x_check.astype(np.float64)
  for W, b, act in zip(weights, biases, activations):
    x_np = x_np @ W +b
    if act == "relu":
      x_np = np.maximum(x_np, 0)
    elif act == "linear":
      pass
    else:
      raise ValueError(f"Self-check doesn't handle validation {act}")
  if not np.allclose(x_np, y_keras, atol = 1e-4):
    raise RuntimeError(
        f"Export check failed: numpy forward pass ({x_np}) does not"
        f"match model.predict ({y_keras}). Do not trust the exported"
        f".mat file until this is fixed"
    )
  print(" Export self-check passed: numpy-reconstructed forward "
  "matches model.predict()")

