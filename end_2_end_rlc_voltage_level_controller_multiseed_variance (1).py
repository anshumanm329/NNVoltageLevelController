# Import the required libraries
import argparse, json, os, random
from pathlib import Path

import numpy as np
import pandas as pd
import scipy.io as sio
from sklearn.model_selection import train_test_split
import tensorflow as tf
import tf_keras as tfk

"""## 1.1. Declare the global variables for this program"""

## ================================================= ##
## CONFIG ##
## ================================================= ##
X_PATH = "/content/drive/MyDrive/X_data_MPC_for_training.csv"
Y_PATH = "/content/drive/MyDrive/y_data_MPC_for_training.csv"
SAVE_DIR = "/content/drive/MyDrive/nn_controller_data"
OUT_ROOT = "/content/drive/MyDrive/nn_controller_data/multi_seed_variance/nn_runs"
SEEDS = [48, 1, 2, 3, 4, 5, 6, 7, 8, 9]
ABLATIONS = {
    "full": [],
    "no_Vc": ["Vc"],
    "no_IL": ["IL"],
    "no_Vc_no_IL": ["Vc", "IL"]
}
# Keras verbosity
FIT_VERBOSE = 0

FEATURES_ALL = ["setpoint", "Vout", "Vout (t-1)", "Vout (t-2)", "Vout (t-3)",
                "Vout (t-4)", "Vout (t-5)", "Vc", "IL", "Iload"]
LABEL = "Controller_action"
TRAJ = "traj_id"

SPLIT_SEED = 48          # fixed: identical partition for every run
TEST_SETPOINTS = [15, 22]
VAL_FRACTION = 0.2

HIDDEN_LAYERS = [256, 128, 64, 32, 16]
ACTIVATION = "relu"
LEARNING_RATE = 1e-3
BATCH_SIZE = 256
MAX_EPOCHS = 500
EARLY_STOP_PATIENCE = 20
U_MIN, U_MAX = 0.0, 5.0

"""## 1.2. Function to assign different random seeds

The base seed is 48, however, in the program instead of just one seed, the script will be run using different random seeds
"""

def set_seeds(seed):
    os.environ["PYTHONHASHSEED"] = str(seed)
    random.seed(seed)
    np.random.seed(seed)
    import tensorflow as tf
    tf.random.set_seed(seed)
    try:
        tf.config.experimental.enable_op_determinism()
    except AttributeError:
        pass

"""## 1.3. Function to load data"""

def load_dataset(x_path, y_path):
    X = pd.read_csv(x_path, header=None)
    y = pd.read_csv(y_path, header=None)
    if len(X) != len(y):
        raise ValueError(f"row mismatch: X={len(X)}, y={len(y)}")
    if X.shape[1] != len(FEATURES_ALL):
        raise ValueError(f"X has {X.shape[1]} columns, expected {len(FEATURES_ALL)}")
    df = X.copy()
    df.columns = FEATURES_ALL
    df[LABEL] = y.iloc[:, 0].values
    sp = df["setpoint"].values
    changed = np.empty(len(sp), dtype=bool)
    changed[0] = True
    changed[1:] = sp[1:] != sp[:-1]
    df[TRAJ] = np.cumsum(changed)
    return df

"""## 1.4. Function to split the dataset as per trajectories"""

def split_dataset(df):
    test_mask = df["setpoint"].isin(TEST_SETPOINTS)
    test_df = df[test_mask].copy()
    remaining = df[~test_mask].copy()
    ids = remaining[TRAJ].unique()
    train_ids, val_ids = train_test_split(ids, test_size=VAL_FRACTION,
                                          random_state=SPLIT_SEED)
    train_df = remaining[remaining[TRAJ].isin(train_ids)].copy()
    val_df = remaining[remaining[TRAJ].isin(val_ids)].copy()
    return train_df, val_df, test_df

"""## 1.5. Function for normalization"""

def norm_stats(df, columns):
    return {c: {"mean": float(df[c].mean()),
                "std": float(df[c].std() + 1e-8)} for c in columns}
def apply_norm(df, columns, stats):
    out = df.copy()
    for c in columns:
        out[c] = (out[c] - stats[c]["mean"]) / stats[c]["std"]
    return out

"""## 2. Building the model

The model in this case is a simple feed forward neural network based on `tensorflow.keras` with hidden layers having 256, 128, 64, 32 and 16 hidden units respectively. The input layer takes an input of shape (10, ) and the hidden layers have `relu` as their activation function
"""

def build_model(n_inputs, seed):
  # Release the graph built by the previous run before starting a new one
  tfk.backend.clear_session()
  # Set seed
  tf.random.set_seed(seed)
  # Input layer
  inputs = tfk.layers.Input(shape = (n_inputs, ), name = "Input_layer")
  x = inputs
  for units in HIDDEN_LAYERS:
    x = tfk.layers.Dense(units, activation = ACTIVATION)(x)
  outputs = tfk.layers.Dense(1, activation = "linear", name = "Control_action")(x)
  model = tfk.Model(inputs, outputs)
  model.compile(loss = "mse",
                optimizer = tfk.optimizers.Adam(learning_rate = LEARNING_RATE),
                metrics = ["mae"])
  return model # returns the compiled model

"""### 2.1. Function to create a tensorboard callback"""

import datetime
def create_tensorboard_callback(dir_name, experiment_name):
  """
  Function to create a tensorboard callback and save the logs
  at the specified directory under the specified experiment name
  """
  log_dir = dir_name + "/" + experiment_name + "/" + datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
  tensorboard_callback = tfk.callbacks.TensorBoard(log_dir = log_dir)
  print(f"Saving the tensorbord log files to {log_dir}")
  return tensorboard_callback

"""### 2.2. Function to export weights to matlab

"""

def export_weights_for_matlab(model, stats, features, path):
  """
  Function to export weights for a matlab function based
  implementation of a neural network in closed loop simulation
  """
  dense = [layer for layer in model.layers if isinstance(layer, tfk.layers.Dense)]
  mat = {
      "num_layers": len(dense),
      "input_columns": np.array(features, dtype = object),
      "output_column": LABEL,
      "input_mean": np.array([stats[c]["mean"] for c in features]).reshape(1,-1),
      "input_std": np.array([stats[c]["std"] for c in features]).reshape(1,-1),
      "output_mean": stats[LABEL]["mean"],
      "output_std":  stats[LABEL]["std"],
      "u_min": U_MIN,
      "u_max": U_MAX
  }
  Ws, bs, acts = [], [], []
  for i, layer in enumerate(dense, start = 1):
    W, b = layer.get_weights()
    W = W.astype(np.float64); b = b.astype(np.float64).reshape(1,-1)
    act = layer.activation.__name__
    mat[f"W{i}"], mat[f"b{i}"], mat[f"activation{i}"] = W, b, act
    Ws.append(W); bs.append(b); acts.append(act)
  sio.savemat(path, mat)
  # Self check: numpy forward pass through the exported arrays must match keras
  xc = np.random.randn(1, len(features)).astype(np.float32)
  y_keras = model.predict(xc, verbose = 0)
  z = xc.astype(np.float64)
  for W, b, act in zip(Ws, bs, acts):
    z = z @ W + b
    if act == "relu":
      z = np.maximum(z, 0)
    elif act != "linear":
      raise ValueError(f"Unsupported activation {act}")
  if not np.allclose(z, y_keras, atol = 1e-4):
    raise RuntimeError("export self-check failed: numpy! = model.predict")
  return len(dense)

"""### 2.3. Function to denormalize the metrics

A function to denormalize the metrics and reporting the obtained error in Volts
"""

def denorm_metrics(model, d, features, stats):
  """
  Predict on  split and report the error in Volts
  after undoing the label normalization.
  """
  mu = np.array([stats[c]["mean"] for c in features])
  sd = np.array([stats[c]["std"] for c in features])
  Z = ((d[features].values - mu)/ sd).astype(np.float32)
  yp = model.predict(Z, verbose = 0).ravel() * stats[LABEL]["std"] + stats[LABEL]["mean"]
  yt = d[LABEL].values
  err = np.abs(yp - yt)

  summary = {"n": int(len(d)),
             "mae_volts": float(err.mean()),
             "rmse_volts": float(np.sqrt(((yp-yt)**2).mean())),
             "max_abs_err_volts": float(err.max()),
             "mae_normalized": float(err.mean()/stats[LABEL]["std"])}
  return summary, yp, yt

"""## 3. Functions for training

### 3.1. Function to do a single training run
"""

def train_one_run(seed, drop, outdir, df = None):
  """
  Train, evaluate, save and export a single network
  seed - the random seed to set
  drop - list of input channels to remove, we are only considering either Vc or IL or both
  outdir - the directory to which the output is saved
  df - preloaded dataframe to avoid re-reading csvs for every run
  """
  set_seeds(seed)
  import tf_keras as tfk
  unknown = [f for f in drop if f not in FEATURES_ALL]
  if unknown:
    raise ValueError(f"unknown feature(s) to drop: {unknown}")
  features = [f for f in FEATURES_ALL if f not in drop]
  outdir = Path(outdir)
  outdir.mkdir(parents = True, exist_ok = True)
  if df is None:
    df = load_dataset(X_PATH, Y_PATH)
  train_df, val_df, test_df = split_dataset(df)
  stats = norm_stats(train_df, features + [LABEL])
  tr = apply_norm(train_df, features + [LABEL], stats)
  va = apply_norm(val_df, features + [LABEL], stats)
  X_train = tr[features].values.astype(np.float32)
  y_train = tr[LABEL].values.astype(np.float32).reshape(-1,1)
  X_val = va[features].values.astype(np.float32)
  y_val = va[LABEL].values.astype(np.float32).reshape(-1,1)

  model = build_model(len(features), seed)
  callbacks = [
      tfk.callbacks.EarlyStopping(monitor = "val_loss",
                                  patience = EARLY_STOP_PATIENCE,
                                  restore_best_weights=True),
      tfk.callbacks.ReduceLROnPlateau(monitor="val_loss",
                                      patience=10,
                                      min_lr = 1e-6),
      create_tensorboard_callback(SAVE_DIR, "single_training_run")

  ]
  hist = model.fit(X_train, y_train,
                   validation_data = (X_val, y_val),
                   batch_size = BATCH_SIZE,
                   epochs = MAX_EPOCHS,
                   callbacks = callbacks, verbose = FIT_VERBOSE)
  pd.DataFrame(hist.history).to_csv(outdir / "history.csv", index_label = "epoch")
  model.save(outdir/"model.keras")
  n_layers = export_weights_for_matlab(model, stats, features, str(outdir/"nn_weights_for_matlab_multiseed.mat"))
  metrics = {"seed": seed,
             "features": features,
             "dropped": list(drop),
             "n_dense_layers": n_layers,
             "epochs_run": len(hist.history["loss"]),
             "best_epoch": int(np.argmin(hist.history["val_loss"]))+1,
             "best_val_loss": float(np.min(hist.history["val_loss"]))}
  for name, d in (("train", train_df), ("val", val_df), ("test", test_df)):
    metrics[name], _, _ = denorm_metrics(model, d, features, stats)
    # Per setpoint break down on the test set
    _, yp, yt = denorm_metrics(model, test_df, features, stats)
    err_by_sp = test_df.assign(err = np.abs(yp-yt)).groupby("setpoint")["err"]
    mae_sp, max_sp, n_sp = err_by_sp.mean(), err_by_sp.max(), err_by_sp.count()
    metrics["test_per_setpoint"] = {
        int(sp): {"mae_volts": float(mae_sp[sp]),
                  "max_abs_err_volts": float(max_sp[sp]),
                  "n": int(n_sp[sp])}
        for sp in mae_sp.index
    }
  metrics["norm_stats"] = stats
  with open(outdir / "metrics.json", "w") as f:
    json.dump(metrics, f, indent = 2)
  return metrics

"""### 3.2. Function to run the full sweep with all the seeds"""

def run_sweep():
  df_all = load_dataset(X_PATH, Y_PATH)
  print(f"{len(df_all)} samples, {df_all[TRAJ].nunique()} trajectories,"
        f"setpoints {sorted(df_all['setpoint'].unique())}\n")
  rows = []
  for cfg_name, drop in ABLATIONS.items():
    for seed in SEEDS:
      outdir = f"{OUT_ROOT}/{cfg_name}/seed{seed}"
      m = train_one_run(seed, drop, outdir, df = df_all)
      rows.append(dict(configuration = cfg_name,
                       seed = seed,
                       n_inputs = len(m["features"]),
                       epochs = m["epochs_run"],
                       best_epoch = m["best_epoch"],
                       train_mae = m["train"]["mae_volts"],
                       val_mae_V = m["val"]["mae_volts"],
                       test_mae_V = m["test"]["mae_volts"],
                       mae_15V = m["test_per_setpoint"][15]["mae_volts"],
                       mae_22V = m["test_per_setpoint"][22]["mae_volts"],
                       ))
      print(f"{cfg_name:12s} seed {seed:3d} epochs {m['epochs_run']:4d}  "
            f"test MAE {m['test']['mae_volts']:.5f} V")
  results = pd.DataFrame(rows)
  Path(OUT_ROOT).mkdir(parents = True, exist_ok = True)
  results.to_csv(f"{OUT_ROOT}/seed_ablation_results.csv", index = False)
  return results

"""### 3.4. Function to summarize the results"""

def report(results):
  import scipy.stats as st
  summary = (results.groupby("configuration")["test_mae_V"]
             .agg(["mean", "std", "median", "min", "max"])
             .reindex(list(ABLATIONS)))
  print("\ntest MAE in volts across seeds: \n")
  print(summary.to_string(float_format=lambda v: f"{v:.5f}"))
  # Paired tests: every configuration is compared with the full vector
  # seed by seed, so the seed-to-seed spread does not mask the effect of removing a channel
  base = results[results.configuration == "full"].set_index("seed")["test_mae_V"]
  print("\npaired comparison against the full input set (same seeds):\n")
  for cfg in ABLATIONS:
    if cfg == "full":
      continue
    v = results[results.configuration == cfg].set_index("seed")["test_mae_V"]
    v, b = v.align(base, join = "inner")
    delta = (v-b).mean()
    p_t = st.ttest_rel(v, b).pvalue
    p_w = st.wilcoxon(v, b).pvalue
    print(f"{cfg:12s} mean delta = {delta:+.4f} V"
          f"({100 * delta / b.mean():+.1f}) %)"
          f"paired t p = {p_t:.3f} Wilcoxon p = {p_w:.3f}")

if __name__ == "__main__":
  results = run_sweep()
  report(results)
  print(f"\nAll runs written under {OUT_ROOT}/")
  print(f"Summary table: {OUT_ROOT}/seed_ablation_results.csv")

